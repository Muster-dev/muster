_env_cg_default_out() {
  local root="$1" lang="$2" set
  set=$(jq -r --arg l "$lang" '.codegen[$l] // empty' "$(_env_schema_file "$root")" 2>/dev/null)
  if [[ -n "$set" ]]; then
    printf '%s' "$set"
    return 0
  fi
  case "$lang" in
    typescript) if [[ -d "$root/src" ]]; then printf 'src/env.generated.ts'; else printf 'env.generated.ts'; fi ;;
    python) printf 'muster_env.py' ;;
    go) if [[ -f "$root/go.mod" ]]; then printf 'internal/config/env_gen.go'; else printf 'config/env_gen.go'; fi ;;
  esac
}

_env_cmd_codegen() {
  local lang="" out="" pkg="" check=false
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --out | -o) out="${2:-}"; shift 2 ;;
      --out=*) out="${1#*=}"; shift ;;
      --package) pkg="${2:-}"; shift 2 ;;
      --package=*) pkg="${1#*=}"; shift ;;
      --lang) lang="${2:-}"; shift 2 ;;
      --lang=*) lang="${1#*=}"; shift ;;
      --check) check=true; shift ;;
      -*) err "Unknown option: $1"; return 1 ;;
      *) lang="$1"; shift ;;
    esac
  done
  case "$lang" in
    ts | typescript) lang=typescript ;;
    py | python) lang=python ;;
    go | golang) lang=go ;;
    all) ;;
    *) err "Usage: muster env codegen ts|py|go|all [--out PATH] [--package NAME] [--check]"; return 1 ;;
  esac
  _env_cmd_root || return 1
  _env_need_store || return 1
  local root="$_ENV_ROOT" schema
  schema=$(_env_schema_file "$root")
  [[ -f "$schema" ]] || { err "No muster.env.schema.json (muster env init)"; return 1; }
  if [[ "$lang" == "all" ]]; then
    [[ -n "$out" ]] && { err "--out can't be used with all"; return 1; }
    local l rc=0 any=false
    for l in typescript python go; do
      if jq -e --arg l "$l" '.codegen[$l]' "$schema" >/dev/null 2>&1; then
        any=true
        if [[ "$check" == "true" ]]; then
          _env_cmd_codegen "$l" --check || rc=1
        else
          _env_cmd_codegen "$l" || rc=1
        fi
      fi
    done
    [[ "$any" == "false" ]] && { err "No codegen targets in muster.env.schema.json yet (run muster env codegen ts|py|go once)"; return 1; }
    return "$rc"
  fi
  [[ -z "$out" ]] && out=$(_env_cg_default_out "$root" "$lang")
  local abs="$out"
  [[ "$abs" != /* ]] && abs="$root/$out"
  if [[ "$lang" == "go" && -z "$pkg" ]]; then
    pkg=$(basename "$(dirname "$abs")" | tr -c 'a-z0-9_\n' '_' | tr -d '\n')
    [[ "$pkg" =~ ^[a-z_][a-z0-9_]*$ && "$pkg" != "." ]] || pkg="config"
  fi
  local model text prog
  model=$(jq -c "$_CG_MODEL_JQ" "$schema") || { err "Could not read the schema"; return 1; }
  case "$lang" in
    typescript) prog="$_CG_TS_JQ" ;;
    python) prog="$_CG_PY_JQ" ;;
    go) prog="$_CG_GO_JQ" ;;
  esac
  text=$(printf '%s' "$model" | jq -r --arg pkg "${pkg:-config}" "$prog") || { err "Code generation failed"; return 1; }
  if [[ "$lang" == "go" ]] && has_cmd gofmt; then
    text=$(printf '%s\n' "$text" | gofmt 2>/dev/null) || { err "Generated Go did not parse (gofmt)"; return 1; }
  fi
  if [[ "$check" == "true" ]]; then
    if [[ -f "$abs" && "$(cat "$abs")" == "$text" ]]; then
      ok "$out is up to date"
      return 0
    fi
    err "$out is out of date (run: muster env codegen ${lang})"
    return 1
  fi
  mkdir -p "$(dirname "$abs")"
  printf '%s\n' "$text" >"$abs"
  # Remember the target so `codegen all` and --check find it
  _env_jq_update "$schema" "$(_env_schema_default)" '.codegen[$l] = $o' --arg l "$lang" --arg o "$out"
  ok "Wrote $out ($(printf '%s' "$model" | jq '.keys | length') keys, $(printf '%s' "$model" | jq '.flags | length') flags)"
}
