			r.fail(key + \" is required\")
		}
		for _, s := range ru.requiredIn {
			if s == r.stage {
				r.fail(key + \" is required in \" + r.stage)
			}
		}
		return \"\", false
	}
	if len(ru.enum) > 0 {
		found := false
		for _, e := range ru.enum {
			found = found || e == v
		}
		if !found {
			r.fail(key + \" must be one of: \" + strings.Join(ru.enum, \", \"))
		}
	}
	if ru.pattern != \"\" {
		if re, err := regexp.Compile(ru.pattern); err != nil || !re.MatchString(v) {
			if secret {
				r.fail(key + \" does not match its pattern\")
			} else {
				r.fail(key + \" does not match \" + ru.pattern)
			}
		}
	}
	if re, ok := formats[ru.format]; ok && !re.MatchString(v) {
		r.fail(key + \" must be a \" + ru.format)
	}
	return v, true
}

func (r *reader) str(key string, ru rule) string {
	v, _ := r.raw(key, ru, false)
	return v
}

func (r *reader) secret(key string, ru rule) Secret {
	v, _ := r.raw(key, ru, true)
	return Secret{v: v}
}

func (r *reader) number(key string, ru rule) float64 {
	v, ok := r.raw(key, ru, false)
	if !ok {
		return 0
	}
	n, err := strconv.ParseFloat(strings.TrimSpace(v), 64)
	if err != nil {
		r.fail(key + \" must be a number\")
		return 0
	}
	if ru.hasMin && n < ru.min {
		r.fail(key + \" must be >= \" + strconv.FormatFloat(ru.min, \u0027g\u0027, -1, 64))
	}
	if ru.hasMax && n > ru.max {
		r.fail(key + \" must be <= \" + strconv.FormatFloat(ru.max, \u0027g\u0027, -1, 64))
	}
	return n
}

func (r *reader) integer(key string, ru rule) int {
	v, ok := r.raw(key, ru, false)
	if !ok {
		return 0
	}
	n, err := strconv.Atoi(strings.TrimSpace(v))
	if err != nil {
		r.fail(key + \" must be an integer\")
		return 0
	}
	if ru.hasMin && float64(n) < ru.min {
		r.fail(key + \" must be >= \" + strconv.FormatFloat(ru.min, \u0027g\u0027, -1, 64))
	}
	if ru.hasMax && float64(n) > ru.max {
		r.fail(key + \" must be <= \" + strconv.FormatFloat(ru.max, \u0027g\u0027, -1, 64))
	}
	return n
}

func (r *reader) boolean(key string, ru rule) bool {
	v, ok := r.raw(key, ru, false)
	if !ok {
		return false
	}
	switch strings.ToLower(v) {
	case \"true\", \"1\":
		return true
	case \"false\", \"0\":
		return false
	}
	r.fail(key + \" must be true or false\")
	return false
}

func (r *reader) jsonValue(key string, ru rule) json.RawMessage {
	v, ok := r.raw(key, ru, false)
	if !ok {
		return nil
	}
	if !json.Valid([]byte(v)) {
		r.fail(key + \" must be valid JSON\")
		return nil
	}
	return json.RawMessage(v)
}

func (r *reader) flagBool(name string, def bool) bool {
	v, ok := r.lookup(name)
	if !ok || v == \"\" {
		return def
	}
	switch strings.ToLower(v) {
	case \"true\", \"1\", \"on\":
		return true
	}
	return false
}

func (r *reader) flagString(name, def string) string {
	if v, ok := r.lookup(name); ok {
		return v
	}
	return def
}

func (r *reader) flagNumber(name string, def float64) float64 {
	v, ok := r.lookup(name)
	if !ok {
		return def
	}
	n, err := strconv.ParseFloat(v, 64)
	if err != nil {
		return def
	}
	return n
}

func (r *reader) flagJSON(name, def string) json.RawMessage {
	if v, ok := r.lookup(name); ok && json.Valid([]byte(v)) {
		return json.RawMessage(v)
	}
	return json.RawMessage(def)
}
